// Package llmproxy is the LLM proxy: an embeddable http.Handler that passes
// native Anthropic Messages traffic through to the upstream untouched, the
// caller's credentials included, and hands one usage record per request to a
// usage sink the host provides.
package llmproxy

import (
	"context"
	"errors"
	"fmt"
	"log/slog"
	"net/http"
	"net/url"
	"time"
)

// DefaultAttributionHeader is the request header carrying the attribution.
const DefaultAttributionHeader = "X-Llm-Attribution"

// Config configures the LLM proxy.
type Config struct {
	Upstream          string       // default "https://api.anthropic.com"
	AttributionHeader string       // default DefaultAttributionHeader
	Sink              UsageSink    // required
	Client            *http.Client // optional; default has no overall timeout (streams are long)
	Logger            *slog.Logger // optional
}

// UsageSink receives the usage records of the LLM proxy.
type UsageSink interface {
	// Record is called exactly once per proxied request, after the response has
	// been fully written to the client (or the client went away / upstream
	// failed). It runs off the response path; a slow or panicking sink never
	// delays, fails or truncates the LLM response. ctx is not the request's.
	Record(ctx context.Context, r UsageRecord)
}

// UsageRecord is what one proxied request used.
type UsageRecord struct {
	ID                       string // unique per request, generated by the proxy
	Attribution              string // header value, "" if absent
	Method                   string
	Path                     string // upstream path, e.g. "/v1/messages"
	Model                    string // from the response (message / message_start), else the request body's "model", else ""
	Status                   int    // upstream HTTP status; 0 if upstream was never reached
	Streamed                 bool   // response was text/event-stream
	StartedAt                time.Time
	EndedAt                  time.Time
	InputTokens              int64
	OutputTokens             int64
	CacheCreationInputTokens int64
	CacheReadInputTokens     int64
	Error                    string // transport error or client disconnect; "" on a completed response
}

// New returns a handler that forwards every request it receives to Upstream,
// at the same path and query (the host mounts it with http.StripPrefix).
func New(cfg Config) (http.Handler, error) {
	if cfg.Sink == nil {
		return nil, errors.New("llmproxy: Config.Sink is required")
	}
	if cfg.Upstream == "" {
		cfg.Upstream = "https://api.anthropic.com"
	}
	upstream, err := url.Parse(cfg.Upstream)
	if err != nil {
		return nil, fmt.Errorf("llmproxy: invalid Upstream %q: %w", cfg.Upstream, err)
	}
	if upstream.Scheme == "" || upstream.Host == "" {
		return nil, fmt.Errorf("llmproxy: Upstream %q must be an absolute URL", cfg.Upstream)
	}
	if cfg.AttributionHeader == "" {
		cfg.AttributionHeader = DefaultAttributionHeader
	}
	if cfg.Logger == nil {
		cfg.Logger = slog.Default()
	}
	return &handler{
		upstream:          upstream,
		attributionHeader: http.CanonicalHeaderKey(cfg.AttributionHeader),
		sink:              cfg.Sink,
		client:            passThroughClient(cfg.Client),
		log:               cfg.Logger,
	}, nil
}

// passThroughClient returns the client the LLM proxy forwards with: a copy of
// the host's, or one with no overall timeout. Redirects are never followed:
// they go back to the caller as they are. Accept-Encoding is left to the
// caller, so an *http.Transport never adds gzip and decodes the response.
func passThroughClient(host *http.Client) *http.Client {
	c := &http.Client{}
	if host != nil {
		*c = *host
	}
	switch t := c.Transport.(type) {
	case nil:
		c.Transport = noCompression(http.DefaultTransport.(*http.Transport))
	case *http.Transport:
		c.Transport = noCompression(t)
	}
	c.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }
	return c
}

func noCompression(t *http.Transport) *http.Transport {
	t = t.Clone()
	t.DisableCompression = true
	return t
}
